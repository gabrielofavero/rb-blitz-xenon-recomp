# Generate explicit Inno [Files] entries for every validated authored layout.
# An empty include is valid when no layouts are supplied with the build.
param(
    [string]$Output,
    [string]$SourceRoot
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (-not $Output) { $Output = Join-Path $repoRoot 'installer/out/generated/controller_schemes.iss' }
if (-not $SourceRoot) { $SourceRoot = Join-Path $repoRoot 'assets/controller' }
$SourceRoot = [IO.Path]::GetFullPath($SourceRoot)
$validator = Join-Path $repoRoot 'out/build/win-amd64-release/rb_blitz_controller_schemes.exe'
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('; Generated by installer/tools/stage_controller_schemes.ps1.')
$folders = @()
if (Test-Path -LiteralPath $SourceRoot -PathType Container) {
    $folders = @(Get-ChildItem -LiteralPath $SourceRoot -Directory |
        Where-Object { $_.Name -notlike 'template-*' -and
            (Test-Path -LiteralPath (Join-Path $_.FullName 'scheme.toml')) } |
        Sort-Object Name)
}
$retailHashes = [System.Collections.Generic.HashSet[string]]::new()
if ($folders.Count -gt 0) {
    # Exact copies of locally exported game art must never enter a release.
    foreach ($reference in @('template-360', 'template-ps3')) {
        $referenceRoot = Join-Path $repoRoot "assets/controller/$reference"
        if (Test-Path -LiteralPath $referenceRoot -PathType Container) {
            Get-ChildItem -LiteralPath $referenceRoot -Recurse -File -Filter '*.png' |
                ForEach-Object { [void]$retailHashes.Add((Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash) }
        }
    }
}
foreach ($entry in $folders) {
    $id = $entry.Name
    $folder = $entry.FullName
    if (-not (Test-Path -LiteralPath $validator -PathType Leaf)) {
        throw "Build rb_blitz_controller_schemes before packaging $id."
    }
    $internal = $id -eq 'keyboard-mouse'
    $mode = if ($internal) { '--validate-internal-keyboard' } else { '--validate' }
    $listMode = if ($internal) { '--list-internal-keyboard' } else { '--list-declared' }
    $report = @(& $validator $mode $folder)
    if ($LASTEXITCODE -ne 0) { throw "Invalid authored controller scheme: $folder" }
    $files = @(& $validator $listMode $folder)
    if ($LASTEXITCODE -ne 0) { throw "Cannot list declared files: $folder" }
    foreach ($relative in $files) {
        $file = Get-Item -LiteralPath (Join-Path $folder $relative)
        if ($file.Extension -eq '.png' -and
            $retailHashes.Contains((Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash)) {
            throw "Authored scheme contains an exact copy of local game art: $($file.FullName)"
        }
        $relative = $relative.Replace('/', '\')
        $source = $file.FullName.Replace('"', '""')
        $destination = if ($internal) { "assets\controller\keyboard-mouse" } else { "assets\controller\schemes\$id" }
        $subdir = Split-Path -Parent $relative
        if ($subdir) { $destination += "\$subdir" }
        $lines.Add("Source: `"$source`"; DestDir: `"{app}\$destination`"; Flags: ignoreversion")
    }
    Write-Host "Staged $id ($($files.Count) files)"
}
$parent = Split-Path -Parent $Output
New-Item -ItemType Directory -Force -Path $parent | Out-Null
[IO.File]::WriteAllLines($Output, $lines, [Text.UTF8Encoding]::new($false))
